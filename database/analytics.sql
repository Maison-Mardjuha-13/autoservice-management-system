-- ============================================================
-- ANALYTICS.SQL
-- Аналитические SQL-запросы для проекта автосервиса
-- ============================================================


-- ============================================================
-- 1. Общее количество заявок
-- ============================================================
-- Показывает, сколько всего заявок на обслуживание
-- зарегистрировано в системе.

SELECT
    COUNT(*) AS total_requests
FROM service_requests;


-- ============================================================
-- 2. Количество заявок по статусам
-- ============================================================
-- Показывает распределение заявок по текущему статусу.
-- Позволяет оценить, сколько заявок новых, подтверждённых,
-- находящихся в работе и завершённых.

SELECT
    status,
    COUNT(*) AS requests_count
FROM service_requests
GROUP BY status
ORDER BY requests_count DESC;


-- ============================================================
-- 3. Количество заявок по месяцам
-- ============================================================
-- Показывает динамику количества заявок по месяцам.
-- Используется для анализа загрузки автосервиса
-- и выявления периодов повышенного спроса.

SELECT
    DATE_TRUNC('month', service_date) AS month,
    COUNT(*) AS requests_count
FROM service_requests
GROUP BY DATE_TRUNC('month', service_date)
ORDER BY month;


-- ============================================================
-- 4. Выручка по месяцам
-- ============================================================
-- Показывает общую стоимость завершённых заказ-нарядов
-- по месяцам.
-- Позволяет анализировать изменение выручки во времени.

SELECT
    DATE_TRUNC('month', sr.service_date) AS month,
    SUM(so.total_cost) AS revenue
FROM service_orders so
JOIN service_requests sr
    ON sr.request_id = so.request_id
WHERE so.status = 'COMPLETED'
GROUP BY DATE_TRUNC('month', sr.service_date)
ORDER BY month;


-- ============================================================
-- 5. Средняя стоимость заказ-наряда
-- ============================================================
-- Рассчитывает среднюю стоимость обслуживания автомобиля.
-- Показатель помогает оценить средний чек автосервиса.

SELECT
    ROUND(AVG(total_cost), 2) AS average_order_cost
FROM service_orders
WHERE status = 'COMPLETED';


-- ============================================================
-- 6. Самые популярные виды работ
-- ============================================================
-- Показывает, какие виды технических работ выполняются
-- чаще всего.
-- Количество рассчитывается по заказ-нарядам.

SELECT
    w.name AS work,
    SUM(ow.quantity) AS times_performed
FROM order_works ow
JOIN works w
    ON w.work_id = ow.work_id
GROUP BY w.work_id, w.name
ORDER BY times_performed DESC;


-- ============================================================
-- 7. Самые востребованные запчасти
-- ============================================================
-- Показывает запчасти, которые чаще всего используются
-- при обслуживании автомобилей.
-- Это может использоваться для планирования закупок.

SELECT
    p.name AS part,
    p.article,
    SUM(op.quantity) AS quantity_used
FROM order_parts op
JOIN parts p
    ON p.part_id = op.part_id
GROUP BY p.part_id, p.name, p.article
ORDER BY quantity_used DESC;


-- ============================================================
-- 8. Клиенты с наибольшим количеством обращений
-- ============================================================
-- Показывает клиентов, которые чаще всего обращались
-- в автосервис.
-- Позволяет определить наиболее активных клиентов.

SELECT
    c.customer_id,
    c.full_name,
    COUNT(sr.request_id) AS requests_count
FROM customers c
JOIN vehicles v
    ON v.customer_id = c.customer_id
JOIN service_requests sr
    ON sr.vehicle_id = v.vehicle_id
GROUP BY c.customer_id, c.full_name
ORDER BY requests_count DESC;


-- ============================================================
-- 9. Автомобили с наибольшим количеством обращений
-- ============================================================
-- Показывает автомобили, которые чаще всего проходили
-- обслуживание.
-- Это позволяет определить автомобили с наиболее высокой
-- частотой обращений.

SELECT
    v.vehicle_id,
    v.brand,
    v.model,
    v.plate_number,
    COUNT(sr.request_id) AS requests_count
FROM vehicles v
JOIN service_requests sr
    ON sr.vehicle_id = v.vehicle_id
GROUP BY
    v.vehicle_id,
    v.brand,
    v.model,
    v.plate_number
ORDER BY requests_count DESC;


-- ============================================================
-- 10. Остатки запчастей, требующие пополнения
-- ============================================================
-- Показывает запчасти с небольшим остатком на складе.
-- В данном примере критическим считается остаток
-- менее 5 единиц.
--
-- Такой показатель может использоваться для контроля склада.

SELECT
    part_id,
    name,
    article,
    quantity,
    price
FROM parts
WHERE quantity < 5
ORDER BY quantity ASC;
