-- ============================================================
-- INDEXES.SQL
-- Индексы для оптимизации работы базы данных автосервиса
-- ============================================================


-- ============================================================
-- 1. Индекс автомобилей по customer_id
-- ============================================================
-- Ускоряет поиск автомобилей конкретного клиента.
-- Используется при соединении customers и vehicles.

CREATE INDEX IF NOT EXISTS idx_vehicles_customer_id
ON vehicles(customer_id);


-- ============================================================
-- 2. Индекс заявок по vehicle_id
-- ============================================================
-- Ускоряет поиск всех заявок конкретного автомобиля.
-- Особенно полезен для просмотра истории обслуживания.

CREATE INDEX IF NOT EXISTS idx_service_requests_vehicle_id
ON service_requests(vehicle_id);


-- ============================================================
-- 3. Индекс заявок по дате обслуживания
-- ============================================================
-- Ускоряет выборку и сортировку заявок по дате.
-- Полезен для анализа загрузки автосервиса во времени.

CREATE INDEX IF NOT EXISTS idx_service_requests_service_date
ON service_requests(service_date);


-- ============================================================
-- 4. Индекс заявок по статусу
-- ============================================================
-- Ускоряет поиск заявок определённого статуса.
-- Например, NEW, CONFIRMED или IN_PROGRESS.

CREATE INDEX IF NOT EXISTS idx_service_requests_status
ON service_requests(status);


-- ============================================================
-- 5. Индекс заказ-нарядов по request_id
-- ============================================================
-- Ускоряет поиск заказ-наряда по конкретной заявке.
-- Используется при соединении service_orders
-- и service_requests.

CREATE INDEX IF NOT EXISTS idx_service_orders_request_id
ON service_orders(request_id);


-- ============================================================
-- 6. Индекс работ в заказ-нарядах по order_id
-- ============================================================
-- Ускоряет поиск всех работ,
-- входящих в конкретный заказ-наряд.

CREATE INDEX IF NOT EXISTS idx_order_works_order_id
ON order_works(order_id);


-- ============================================================
-- 7. Индекс запчастей в заказ-нарядах по order_id
-- ============================================================
-- Ускоряет поиск всех запчастей,
-- использованных в конкретном заказ-наряде.

CREATE INDEX IF NOT EXISTS idx_order_parts_order_id
ON order_parts(order_id);


-- ============================================================
-- 8. Индекс заказ-нарядов по статусу
-- ============================================================
-- Ускоряет фильтрацию заказ-нарядов по статусу.
-- Например, поиск только завершённых заказов.

CREATE INDEX IF NOT EXISTS idx_service_orders_status
ON service_orders(status);
